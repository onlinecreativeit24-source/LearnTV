export function getTodayDailyQuestions(): DailyQuestion[] {
  const startDate = new Date(2026, 0, 1);
  const today = new Date();

  const startUTC = Date.UTC(
    startDate.getFullYear(),
    startDate.getMonth(),
    startDate.getDate()
  );

  const todayUTC = Date.UTC(
    today.getFullYear(),
    today.getMonth(),
    today.getDate()
  );

  const daysSinceStart = Math.floor(
    (todayUTC - startUTC) / (1000 * 60 * 60 * 24)
  );

  const dayIndex =
    ((daysSinceStart % dailyQuestionBank.length) +
      dailyQuestionBank.length) %
    dailyQuestionBank.length;

  return dailyQuestionBank[dayIndex];
}